// Report descriptors made by hand, for tests of interfaces the surveys didn't record: a touchscreen
// that is only a mouse, an ordinary mouse and a joystick.

public enum HandMadeDescriptors {
    /// A touchscreen that is only a mouse: a Pointer application collection (report ID 2) with two
    /// buttons, six bits of padding, and an absolute X and Y of 16 bits each (0…32767).
    public static let absolutePointer: [UInt8] = [
        0x05, 0x01, 0x09, 0x01, 0xA1, 0x01, 0x85, 0x02,
        0x05, 0x09, 0x19, 0x01, 0x29, 0x02, 0x15, 0x00, 0x25, 0x01, 0x75, 0x01, 0x95, 0x02, 0x81, 0x02,
        0x75, 0x06, 0x95, 0x01, 0x81, 0x03,
        0x05, 0x01, 0x09, 0x30, 0x09, 0x31, 0x16, 0x00, 0x00, 0x26, 0xFF, 0x7F, 0x75, 0x10, 0x95, 0x02, 0x81, 0x02,
        0xC0,
    ]

    /// One report of `absolutePointer`: report ID 2, the buttons, then X and Y, each 0…1 across 0…32767.
    public static func absolutePointerReport(buttons: UInt8, x: Double, y: Double) -> [UInt8] {
        let rawX = UInt16(x * 32767), rawY = UInt16(y * 32767)
        return [0x02, buttons, UInt8(rawX & 0xFF), UInt8(rawX >> 8), UInt8(rawY & 0xFF), UInt8(rawY >> 8)]
    }

    /// An ordinary mouse, with no report IDs: a Mouse application collection, a Pointer physical
    /// collection, three buttons, five bits of padding, and a relative X and Y of 8 bits each.
    public static let relativeMouse: [UInt8] = [
        0x05, 0x01, 0x09, 0x02, 0xA1, 0x01, 0x09, 0x01, 0xA1, 0x00,
        0x05, 0x09, 0x19, 0x01, 0x29, 0x03, 0x15, 0x00, 0x25, 0x01, 0x75, 0x01, 0x95, 0x03, 0x81, 0x02,
        0x75, 0x05, 0x95, 0x01, 0x81, 0x03,
        0x05, 0x01, 0x09, 0x30, 0x09, 0x31, 0x15, 0x81, 0x25, 0x7F, 0x75, 0x08, 0x95, 0x02, 0x81, 0x06,
        0xC0, 0xC0,
    ]

    /// A joystick: an absolute X and Y of 8 bits in a Joystick application collection.
    public static let joystick: [UInt8] = [
        0x05, 0x01, 0x09, 0x04, 0xA1, 0x01,
        0x09, 0x30, 0x09, 0x31, 0x15, 0x00, 0x26, 0xFF, 0x00, 0x75, 0x08, 0x95, 0x02, 0x81, 0x02,
        0xC0,
    ]
}
